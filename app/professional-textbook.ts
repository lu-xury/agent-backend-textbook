import type { DeepChapter, DeepUnit, LanguageId } from "./volume/types";

type UnitInput = {
  title: string;
  question: string;
  paragraphs: string[];
  mechanism: Array<[string, string]>;
  example: { situation: string; misconception: string; conclusion: string };
  language: Record<LanguageId, string[]>;
  lab: { goal: string; steps: string[]; checks: string[] };
};

function unit(chapter: number, index: number, input: UnitInput): DeepUnit {
  return {
    id: `chapter-${chapter}-${index}`,
    title: `${chapter}.${index} ${input.title}`,
    readingTime: "约 18–25 分钟",
    question: input.question,
    paragraphs: input.paragraphs,
    mechanismSteps: input.mechanism.map(([title, detail]) => ({ title, detail })),
    caseStudy: {
      symptom: input.example.situation,
      evidence: [],
      analysis: [input.example.misconception],
      correction: [input.example.conclusion],
    },
    languageComparison: input.language,
    lab: input.lab,
    review: [],
  };
}

function chapter(number: number, title: string, preface: string[], units: UnitInput[]): DeepChapter {
  return { number, title, preface, units: units.map((item, index) => unit(number, index + 1, item)) };
}

